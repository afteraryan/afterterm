// afterterm Setup: the installer people run (afterterm-<version>-setup.exe).
//
// It shows the four screens (Setup.xaml) and does the work through two programs:
//   - the engine, electron-builder's one-click NSIS installer, embedded here as the
//     resource "engine.exe" and run silently: it copies the app and creates the
//     shortcuts, the Settings > Apps entry and the uninstaller;
//   - the installed afterterm itself, `afterterm.exe --setup-check=<file>`, which
//     registers and tests the Claude Code helper (src/setup-check.ts).
//
// Built by scripts/build-installer.js with the C# compiler that ships with Windows
// (.NET Framework 4, C# 5: no string interpolation, no ?.), against WPF. Config.cs,
// generated by that script, holds the product name, version and expected size.

using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Threading;
using System.Threading.Tasks;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Interop;
using System.Windows.Markup;
using System.Windows.Media;
using System.Windows.Media.Animation;
using System.Windows.Shapes;
using System.Windows.Threading;
using Microsoft.Win32;

static class Program
{
    [STAThread]
    static int Main()
    {
        var app = new Application();
        var setup = new SetupWindow();
        return app.Run(setup.Window);
    }
}

class SetupWindow
{
    public Window Window;
    string folder;
    string tempDir;
    long bytesSoFar;
    double engineCopied;
    volatile bool engineDone;
    int engineExit = -1;
    bool busy;
    Dictionary<string, string> check = new Dictionary<string, string>();
    string report = "";
    string issueUrl = "";

    T Find<T>(string name) where T : class { return Window.FindName(name) as T; }

    public SetupWindow()
    {
        using (var s = Assembly.GetExecutingAssembly().GetManifestResourceStream("Setup.xaml"))
            Window = (Window)XamlReader.Load(s);

        Window.Title = Config.ProductName + " Setup";
        Find<TextBlock>("WelcomeName").Text = Config.ProductName;
        Find<TextBlock>("WelcomeVersion").Text = "Version " + Config.Version;
        Find<TextBlock>("InstallTitle").Text = "Installing " + Config.ProductName;
        Find<TextBlock>("ReadyTitle").Text = Config.ProductName + " is ready";
        Find<CheckBox>("OpenCb").Content = "Open " + Config.ProductName;

        folder = ExistingInstallFolder() ?? System.IO.Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Programs", Config.FolderName);
        ShowFolder();

        // Test runs place the window themselves (on a second display, away from the
        // person at the machine); nobody else sets these.
        double x, y;
        if (double.TryParse(Environment.GetEnvironmentVariable("AFTERTERM_INSTALLER_X"), out x) &&
            double.TryParse(Environment.GetEnvironmentVariable("AFTERTERM_INSTALLER_Y"), out y))
        {
            Window.WindowStartupLocation = WindowStartupLocation.Manual;
            Window.Left = x;
            Window.Top = y;
        }

        Window.SourceInitialized += delegate { DarkTitleBar(); };
        Window.Closing += (s, e) => { if (busy) e.Cancel = true; };
        Window.Closed += delegate { CleanUp(); };

        Find<Button>("ChangeBtn").Click += delegate { ChangeFolder(); };
        Find<Button>("WelcomeCancel").Click += delegate { Window.Close(); };
        Find<Button>("InstallBtn").Click += delegate { StartInstall(); };
        Find<Button>("InstallClose").Click += delegate { Window.Close(); };
        Find<Button>("CheckNext").Click += delegate { ShowPage("PageReady"); };
        Find<Button>("ReportBtn").Click += delegate { OpenSheet(); };
        Find<Button>("SeeBtn").Click += delegate { ToggleReport(); };
        Find<Button>("SheetCancel").Click += delegate { CloseSheet(); };
        Find<Button>("SheetDone").Click += delegate { CloseSheet(); };
        Find<Button>("SheetOpen").Click += delegate { OpenIssue(); };
        Find<Button>("FinishBtn").Click += delegate { Finish(); };
    }

    // ─── Window ────────────────────────────────────────────────────────────────

    [DllImport("dwmapi.dll")] static extern int DwmSetWindowAttribute(IntPtr hwnd, int attr, ref int value, int size);

    void DarkTitleBar()
    {
        var hwnd = new WindowInteropHelper(Window).Handle;
        int on = 1;
        DwmSetWindowAttribute(hwnd, 20, ref on, 4);      // DWMWA_USE_IMMERSIVE_DARK_MODE
        int caption = 0x001A1A1A;
        DwmSetWindowAttribute(hwnd, 35, ref caption, 4); // DWMWA_CAPTION_COLOR (Windows 11)
    }

    void ShowPage(string name)
    {
        foreach (var p in new[] { "PageWelcome", "PageInstall", "PageCheck", "PageReady" })
        {
            var g = Find<Grid>(p);
            g.Visibility = p == name ? Visibility.Visible : Visibility.Collapsed;
            if (p != name) continue;
            var move = new TranslateTransform(0, 6);
            g.RenderTransform = move;
            var ease = new CubicEase { EasingMode = EasingMode.EaseOut };
            g.BeginAnimation(UIElement.OpacityProperty, new DoubleAnimation(0, 1, TimeSpan.FromMilliseconds(280)) { EasingFunction = ease });
            move.BeginAnimation(TranslateTransform.YProperty, new DoubleAnimation(6, 0, TimeSpan.FromMilliseconds(280)) { EasingFunction = ease });
        }
    }

    // ─── 1. Welcome ────────────────────────────────────────────────────────────

    // A previous install of this product, from its Settings > Apps entry.
    static string ExistingInstallFolder()
    {
        try
        {
            using (var key = Registry.CurrentUser.OpenSubKey(@"Software\Microsoft\Windows\CurrentVersion\Uninstall"))
            {
                if (key == null) return null;
                foreach (var sub in key.GetSubKeyNames())
                {
                    using (var k = key.OpenSubKey(sub))
                    {
                        if (k == null) continue;
                        if ((k.GetValue("DisplayName") as string) != Config.ProductName) continue;
                        var loc = k.GetValue("InstallLocation") as string;
                        if (!string.IsNullOrEmpty(loc)) return loc;
                    }
                }
            }
        }
        catch { }
        return null;
    }

    // The folder, shortened in the middle when it is long, so both ends stay visible.
    void ShowFolder()
    {
        var t = Find<TextBlock>("FolderText");
        t.Text = folder.Length <= 50 ? folder : folder.Substring(0, 18) + "…" + folder.Substring(folder.Length - 30);
        t.ToolTip = folder;
    }

    void ChangeFolder()
    {
        var picked = FolderPicker.Pick(new WindowInteropHelper(Window).Handle, "Choose where to install " + Config.ProductName, folder);
        if (picked == null) return;
        if (!string.Equals(System.IO.Path.GetFileName(picked.TrimEnd('\\')), Config.FolderName, StringComparison.OrdinalIgnoreCase))
            picked = System.IO.Path.Combine(picked, Config.FolderName);
        folder = picked;
        ShowFolder();
    }

    // afterterm running from the folder being installed into: it holds files the
    // engine would replace, and the user's terminals, so it is never closed for them.
    bool AppRunningInFolder()
    {
        var name = System.IO.Path.GetFileNameWithoutExtension(Config.ExeName);
        foreach (var p in Process.GetProcessesByName(name))
        {
            try
            {
                var path = p.MainModule.FileName;
                if (path.StartsWith(folder.TrimEnd('\\') + "\\", StringComparison.OrdinalIgnoreCase)) return true;
            }
            catch { }
        }
        return false;
    }

    // ─── 2. Installing ─────────────────────────────────────────────────────────

    void StartInstall()
    {
        var msg = Find<TextBlock>("WelcomeMsg");
        if (AppRunningInFolder())
        {
            msg.Text = Config.ProductName + " is open. Close it, then click Install.";
            msg.Visibility = Visibility.Visible;
            return;
        }
        msg.Visibility = Visibility.Collapsed;

        busy = true;
        ShowPage("PageInstall");
        bool desktop = Find<CheckBox>("DesktopCb").IsChecked == true;
        bool startMenu = Find<CheckBox>("StartCb").IsChecked == true;

        tempDir = System.IO.Path.Combine(System.IO.Path.GetTempPath(), "afterterm-setup-" + Guid.NewGuid().ToString("N").Substring(0, 8));
        Directory.CreateDirectory(tempDir);
        var started = DateTime.UtcNow;

        Task.Run(() => RunEngine(desktop, startMenu));
        Task.Run(() => MeasureFolder());

        // The bar follows the real work: the engine being unpacked (the first 12%),
        // then the app's bytes arriving in the folder. Between them the engine
        // unpacks its own archive, which nothing can watch, so a slow creep keeps
        // the bar moving there. It never fills faster than 3 seconds and eases
        // toward its target, so it never jumps or stalls.
        double shown = 0;
        var timer = new DispatcherTimer(DispatcherPriority.Render) { Interval = TimeSpan.FromMilliseconds(16) };
        timer.Tick += delegate
        {
            double secs = (DateTime.UtcNow - started).TotalSeconds;
            double folderFrac = (double)Interlocked.Read(ref bytesSoFar) / Math.Max(1, Config.ExpectedBytes);
            double real = 0.12 * Interlocked.CompareExchange(ref engineCopied, 0, 0) + 0.88 * Math.Min(1, folderFrac);
            double creep = 0.85 * (1 - Math.Exp(-secs / 10.0));
            double working = engineDone ? 1 : Math.Min(0.97, Math.Max(real, creep));
            double byTime = Math.Min(1, secs / 3.0);
            double target = Math.Min(working, byTime);
            shown += (target - shown) * 0.12;
            if (target - shown < 0.002) shown = target;
            Find<Border>("Bar").Width = 340 * shown;
            Find<TextBlock>("Pct").Text = ((int)Math.Round(shown * 100)) + "%";
            if (engineDone && shown >= 1)
            {
                timer.Stop();
                AfterEngine();
            }
        };
        timer.Start();
    }

    void RunEngine(bool desktop, bool startMenu)
    {
        try
        {
            var engine = System.IO.Path.Combine(tempDir, "afterterm-engine.exe");
            using (var res = Assembly.GetExecutingAssembly().GetManifestResourceStream("engine.exe"))
            using (var file = File.Create(engine))
            {
                var buf = new byte[1 << 20];
                long done = 0;
                int n;
                while ((n = res.Read(buf, 0, buf.Length)) > 0)
                {
                    file.Write(buf, 0, n);
                    done += n;
                    Interlocked.Exchange(ref engineCopied, (double)done / res.Length);
                }
            }
            // /D= must come last and unquoted (NSIS reads the rest of the line).
            var args = "/S" + (desktop ? "" : " --no-desktop-shortcut") + (startMenu ? "" : " --no-start-menu-shortcut") + " /D=" + folder;
            var p = Process.Start(new ProcessStartInfo(engine, args) { UseShellExecute = false, CreateNoWindow = true });
            p.WaitForExit();
            engineExit = p.ExitCode;
        }
        catch (Exception e)
        {
            engineExit = -2;
            report = e.Message;
        }
        engineDone = true;
    }

    void MeasureFolder()
    {
        while (!engineDone)
        {
            long total = 0;
            try
            {
                if (Directory.Exists(folder))
                    foreach (var f in new DirectoryInfo(folder).EnumerateFiles("*", SearchOption.AllDirectories))
                    {
                        try { total += f.Length; } catch { }
                    }
            }
            catch { }
            Interlocked.Exchange(ref bytesSoFar, total);
            Thread.Sleep(300);
        }
    }

    void AfterEngine()
    {
        var exe = System.IO.Path.Combine(folder, Config.ExeName);
        if (engineExit != 0 || !File.Exists(exe))
        {
            busy = false;
            Find<TextBlock>("InstallTitle").Text = Config.ProductName + " could not be installed";
            var err = Find<TextBlock>("InstallError");
            err.Text = engineExit == 2 || AppRunningInFolder()
                ? Config.ProductName + " is open. Close it and run Setup again."
                : "The installer stopped with error " + engineExit + ". Nothing else on this PC was changed.";
            err.Visibility = Visibility.Visible;
            Find<TextBlock>("Pct").Visibility = Visibility.Collapsed;
            Find<Button>("InstallCancel").Visibility = Visibility.Collapsed;
            Find<Button>("InstallClose").Visibility = Visibility.Visible;
            return;
        }
        busy = false;
        // No Claude Code on this PC: nothing to check and nothing to say about it.
        // afterterm connects to it by itself once it is installed.
        if (!ClaudeOnMachine())
        {
            ShowPage("PageReady");
            return;
        }
        StartCheck(exe);
    }

    static bool ClaudeOnMachine()
    {
        var path = Environment.GetEnvironmentVariable("PATH") ?? "";
        foreach (var dir in path.Split(';'))
        {
            if (dir.Trim().Length == 0) continue;
            try
            {
                if (File.Exists(System.IO.Path.Combine(dir.Trim(), "claude.exe")) ||
                    File.Exists(System.IO.Path.Combine(dir.Trim(), "claude.cmd"))) return true;
            }
            catch { }
        }
        var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        var roaming = Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData);
        return File.Exists(System.IO.Path.Combine(home, @".local\bin\claude.exe")) ||
               File.Exists(System.IO.Path.Combine(roaming, @"npm\claude.cmd"));
    }

    // ─── 3. Checking Claude Code ───────────────────────────────────────────────

    void RunCheck(string exe)
    {
        var ini = System.IO.Path.Combine(tempDir, "check.ini");
        try
        {
            var p = Process.Start(new ProcessStartInfo(exe, "\"--setup-check=" + ini + "\"") { UseShellExecute = false });
            if (!p.WaitForExit(90000)) { try { p.Kill(); } catch { } }
            foreach (var line in File.ReadAllLines(ini))
            {
                var i = line.IndexOf('=');
                if (i > 0) check[line.Substring(0, i).Trim()] = line.Substring(i + 1).Trim();
            }
            report = File.ReadAllText(ini + ".report.txt");
            issueUrl = File.ReadAllText(ini + ".issue.txt").Trim();
        }
        catch { }
    }

    string Value(string key) { string v; return check.TryGetValue(key, out v) ? v : ""; }

    // The Check page shows at once with three spinners, which turn while the check
    // really runs (a few seconds: it starts PowerShell). The first row ticks after
    // half a second (Claude Code was just found); the other two settle when the
    // answer is in, 0.6 s apart, and never before 1.3 s.
    void StartCheck(string exe)
    {
        ShowPage("PageCheck");
        var icons = new[] { Find<ContentControl>("Ic1"), Find<ContentControl>("Ic2"), Find<ContentControl>("Ic3") };
        var texts = new[] { Find<TextBlock>("T1"), Find<TextBlock>("T2"), Find<TextBlock>("T3") };
        foreach (var ic in icons) ic.Content = Spinner();
        var shownAt = DateTime.UtcNow;
        After(500, () => Settle(icons[0], texts[0], true));

        Task.Run(() => RunCheck(exe)).ContinueWith(_ => Window.Dispatcher.Invoke(new Action(() =>
        {
            bool notif = Value("notifications") == "ok";
            bool resume = Value("resume") == "ok";
            var reason = Value("reason");
            if (reason.Length > 0) Find<TextBlock>("Note").Text = reason + " " + Config.ProductName + " works, without these two.";
            int wait = Math.Max(0, 1300 - (int)(DateTime.UtcNow - shownAt).TotalMilliseconds);
            After(wait, () =>
            {
                Settle(icons[1], texts[1], notif);
                if (!notif) Find<TextBlock>("Note").Visibility = Visibility.Visible;
            });
            After(wait + 600, () =>
            {
                Settle(icons[2], texts[2], resume);
                CheckDone(notif && resume);
            });
        })));
    }

    void Settle(ContentControl icon, TextBlock text, bool ok)
    {
        icon.Content = Mark(ok);
        text.Foreground = new SolidColorBrush(Color.FromRgb(0xEC, 0xEC, 0xEC));
    }

    static void After(int ms, Action action)
    {
        var t = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(Math.Max(1, ms)) };
        t.Tick += delegate { t.Stop(); action(); };
        t.Start();
    }

    void CheckDone(bool ok)
    {
        Find<TextBlock>("CheckTitle").Text = ok ? "Claude Code is ready" : "Claude Code needs attention";
        var next = Find<Button>("CheckNext");
        next.IsEnabled = true;
        if (!ok)
        {
            next.Content = "Continue anyway";
            if (issueUrl.Length > 0) Find<Button>("ReportBtn").Visibility = Visibility.Visible;
        }
        next.Focus();
    }

    // A ring with a bright arc, turning (on the render thread, so it never stutters).
    static UIElement Spinner()
    {
        var g = new Grid { Width = 16, Height = 16, RenderTransformOrigin = new Point(0.5, 0.5) };
        g.Children.Add(new Ellipse { Stroke = new SolidColorBrush(Color.FromRgb(0x44, 0x44, 0x44)), StrokeThickness = 2 });
        g.Children.Add(new System.Windows.Shapes.Path
        {
            Data = Geometry.Parse("M8,1 A7,7 0 0 1 15,8"),
            Stroke = new SolidColorBrush(Color.FromRgb(0xEC, 0xEC, 0xEC)),
            StrokeThickness = 2,
            StrokeStartLineCap = PenLineCap.Round,
            StrokeEndLineCap = PenLineCap.Round,
        });
        var rot = new RotateTransform();
        g.RenderTransform = rot;
        rot.BeginAnimation(RotateTransform.AngleProperty, new DoubleAnimation(0, 360, TimeSpan.FromMilliseconds(800)) { RepeatBehavior = RepeatBehavior.Forever });
        return g;
    }

    UIElement Mark(bool ok)
    {
        var img = new Image { Width = 20, Height = 20, Source = (ImageSource)Window.FindResource(ok ? "Tick" : "Cross") };
        var pop = new ScaleTransform(0.6, 0.6);
        img.RenderTransformOrigin = new Point(0.5, 0.5);
        img.RenderTransform = pop;
        var ease = new BackEase { EasingMode = EasingMode.EaseOut, Amplitude = 0.4 };
        pop.BeginAnimation(ScaleTransform.ScaleXProperty, new DoubleAnimation(0.6, 1, TimeSpan.FromMilliseconds(220)) { EasingFunction = ease });
        pop.BeginAnimation(ScaleTransform.ScaleYProperty, new DoubleAnimation(0.6, 1, TimeSpan.FromMilliseconds(220)) { EasingFunction = ease });
        return img;
    }

    // ─── 3b. Report issue ──────────────────────────────────────────────────────

    void OpenSheet()
    {
        Find<TextBox>("ReportBox").Text = report;
        Find<TextBox>("ReportBox").Visibility = Visibility.Collapsed;
        Find<Button>("SeeBtn").Content = "See what's sent";
        Find<StackPanel>("SheetForm").Visibility = Visibility.Visible;
        Find<StackPanel>("SheetSent").Visibility = Visibility.Collapsed;
        Find<Button>("SheetCancel").Visibility = Visibility.Visible;
        Find<Button>("SheetOpen").Visibility = Visibility.Visible;
        Find<Button>("SheetDone").Visibility = Visibility.Collapsed;
        Find<Grid>("Sheet").Visibility = Visibility.Visible;
    }

    void ToggleReport()
    {
        var box = Find<TextBox>("ReportBox");
        bool show = box.Visibility != Visibility.Visible;
        box.Visibility = show ? Visibility.Visible : Visibility.Collapsed;
        Find<Button>("SeeBtn").Content = show ? "Hide" : "See what's sent";
    }

    void CloseSheet() { Find<Grid>("Sheet").Visibility = Visibility.Collapsed; }

    void OpenIssue()
    {
        // Only ever a new issue on afterterm's own repository.
        if (issueUrl.StartsWith("https://github.com/afteraryan/afterterm/issues/new?"))
        {
            try { Process.Start(new ProcessStartInfo(issueUrl) { UseShellExecute = true }); } catch { }
        }
        Find<StackPanel>("SheetForm").Visibility = Visibility.Collapsed;
        Find<StackPanel>("SheetSent").Visibility = Visibility.Visible;
        Find<Button>("SheetCancel").Visibility = Visibility.Collapsed;
        Find<Button>("SheetOpen").Visibility = Visibility.Collapsed;
        Find<Button>("SheetDone").Visibility = Visibility.Visible;
    }

    // ─── 4. Ready ──────────────────────────────────────────────────────────────

    void Finish()
    {
        if (Find<CheckBox>("OpenCb").IsChecked == true)
        {
            try
            {
                Process.Start(new ProcessStartInfo(System.IO.Path.Combine(folder, Config.ExeName)) { UseShellExecute = true, WorkingDirectory = folder });
            }
            catch { }
        }
        Window.Close();
    }

    void CleanUp()
    {
        try { if (tempDir != null) Directory.Delete(tempDir, true); } catch { }
    }
}

// The Windows folder picker (IFileOpenDialog with FOS_PICKFOLDERS), the modern one
// Explorer uses, rather than WinForms' old tree dialog.
static class FolderPicker
{
    [ComImport, Guid("DC1C5A9C-E88A-4dde-A5A1-60F82A20AEF7")] class FileOpenDialogCom { }

    [ComImport, Guid("42f85136-db7e-439c-85f1-e4075d135fc8"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]
    interface IFileOpenDialog
    {
        [PreserveSig] int Show(IntPtr parent);
        void SetFileTypes(uint count, IntPtr specs);
        void SetFileTypeIndex(uint index);
        void GetFileTypeIndex(out uint index);
        void Advise(IntPtr events, out uint cookie);
        void Unadvise(uint cookie);
        void SetOptions(uint options);
        void GetOptions(out uint options);
        void SetDefaultFolder(IShellItem item);
        void SetFolder(IShellItem item);
        void GetFolder(out IShellItem item);
        void GetCurrentSelection(out IShellItem item);
        void SetFileName([MarshalAs(UnmanagedType.LPWStr)] string name);
        void GetFileName([MarshalAs(UnmanagedType.LPWStr)] out string name);
        void SetTitle([MarshalAs(UnmanagedType.LPWStr)] string title);
        void SetOkButtonLabel([MarshalAs(UnmanagedType.LPWStr)] string text);
        void SetFileNameLabel([MarshalAs(UnmanagedType.LPWStr)] string label);
        void GetResult(out IShellItem item);
    }

    [ComImport, Guid("43826D1E-E718-42EE-BC55-A1E261C37BFE"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]
    interface IShellItem
    {
        void BindToHandler(IntPtr pbc, ref Guid bhid, ref Guid riid, out IntPtr ppv);
        void GetParent(out IShellItem item);
        void GetDisplayName(uint sigdn, [MarshalAs(UnmanagedType.LPWStr)] out string name);
    }

    [DllImport("shell32.dll", CharSet = CharSet.Unicode, PreserveSig = false)]
    static extern void SHCreateItemFromParsingName(string path, IntPtr pbc, ref Guid riid, out IShellItem item);

    public static string Pick(IntPtr owner, string title, string start)
    {
        try
        {
            var dlg = (IFileOpenDialog)new FileOpenDialogCom();
            dlg.SetOptions(0x20 | 0x40); // FOS_PICKFOLDERS | FOS_FORCEFILESYSTEM
            dlg.SetTitle(title);
            var dir = start;
            while (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir)) dir = System.IO.Path.GetDirectoryName(dir);
            if (!string.IsNullOrEmpty(dir))
            {
                var iid = typeof(IShellItem).GUID;
                IShellItem item;
                SHCreateItemFromParsingName(dir, IntPtr.Zero, ref iid, out item);
                dlg.SetFolder(item);
            }
            if (dlg.Show(owner) != 0) return null;
            IShellItem result;
            dlg.GetResult(out result);
            string path;
            result.GetDisplayName(0x80058000, out path); // SIGDN_FILESYSPATH
            return path;
        }
        catch { return null; }
    }
}
