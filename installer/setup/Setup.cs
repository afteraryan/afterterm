    void OpenApp()
    {
        var exe = System.IO.Path.Combine(folder, Config.ExeName);
        if (!File.Exists(exe)) return;
        try
        {
            Process.Start(new ProcessStartInfo(exe) { UseShellExecute = true, WorkingDirectory = folder });
        }
        catch { }
    }

    void CleanUp()
    {
        try { if (tempDir != null) Directory.Delete(tempDir, true); } catch { }
    }

    // ─── 5. Updating (update mode) ─────────────────────────────────────────────

    static string DesktopLink()
    {
        return System.IO.Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.DesktopDirectory), Config.ProductName + ".lnk");
    }

    static string StartMenuLink()
    {
        return System.IO.Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Programs), Config.ProductName + ".lnk");
    }

    void StartUpdate(int waitPid)
    {
        var existing = ExistingInstallFolder();
        if (existing == null)
        {
            UpdateFailed(Config.ProductName + " is not installed on this PC.", false);
            return;
        }
        folder = existing;
        busy = true;
        Task.Run(() =>
        {
            bool closed = WaitForApp(waitPid);
            Window.Dispatcher.Invoke(new Action(() =>
            {
                if (!closed)
                {
                    busy = false;
                    UpdateFailed(Config.ProductName + " is still open. Close it and run the update again.", false);
                    return;
                }
                // The shortcuts stay exactly as they are: the engine keeps the ones
                // there are (the uninstall entry's KeepShortcuts), and is told not to
                // make the ones there are not.
                RunInstall(File.Exists(DesktopLink()), File.Exists(StartMenuLink()),
                    Find<Border>("UpdateBar"), 390, Find<TextBlock>("UpdatePct"), AfterUpdateEngine);
            }));
        });
    }

    // The afterterm that started this update quits on its own (it drains its
    // terminals first); after it, nothing may run from the folder being replaced.
    bool WaitForApp(int pid)
    {
        if (pid > 0)
        {
            try
            {
                using (var p = Process.GetProcessById(pid))
                {
                    if (!p.WaitForExit(60000)) return false;
                }
            }
            catch (ArgumentException) { }   // already gone
            catch (InvalidOperationException) { }
        }
        var until = DateTime.UtcNow.AddSeconds(30);
        while (AppRunningInFolder())
        {
            if (DateTime.UtcNow > until) return false;
            Thread.Sleep(300);
        }
        return true;
    }

    void AfterUpdateEngine()
    {
        busy = false;
        var exe = System.IO.Path.Combine(folder, Config.ExeName);
        if (engineExit != 0 || !File.Exists(exe))
        {
            UpdateFailed(engineExit == 2 || AppRunningInFolder()
                ? Config.ProductName + " is open. Close it and run the update again."
                : "The installer stopped with error " + engineExit + ".", File.Exists(exe));
            return;
        }
        OpenApp();
        Window.Close();
    }

    void UpdateFailed(string reason, bool canOpen)
    {
        busy = false;
        Window.Topmost = false;
        Find<TextBlock>("UpdateTitle").Text = Config.ProductName + " could not be updated";
        Find<TextBlock>("UpdatePct").Visibility = Visibility.Collapsed;
        var err = Find<TextBlock>("UpdateError");
        err.Text = reason;
        err.Visibility = Visibility.Visible;
        Find<Border>("UpdateFooter").Visibility = Visibility.Visible;
        if (!canOpen) Find<Button>("UpdateOpen").Visibility = Visibility.Collapsed;
    }
}

// The Windows folder picker (IFileOpenDialog with FOS_PICKFOLDERS), the modern one
// Explorer uses, rather than WinForms' old tree dialog.
static class FolderPicker
{
    [ComImport, Guid("DC1C5A9C-E88A-4dde-A5A1-60F82A20AEF7")] class FileOpenDialogCom { }

    [ComImport, Guid("42f85136-db7e-439c-85f1-e4075d135fc8"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]
    interface IFileOpenDialog
    {
        [PreserveSig] int Show(IntPtr parent);
        void SetFileTypes(uint count, IntPtr specs);
        void SetFileTypeIndex(uint index);
        void GetFileTypeIndex(out uint index);
        void Advise(IntPtr events, out uint cookie);
        void Unadvise(uint cookie);
        void SetOptions(uint options);
        void GetOptions(out uint options);
        void SetDefaultFolder(IShellItem item);
        void SetFolder(IShellItem item);
        void GetFolder(out IShellItem item);
        void GetCurrentSelection(out IShellItem item);
        void SetFileName([MarshalAs(UnmanagedType.LPWStr)] string name);
        void GetFileName([MarshalAs(UnmanagedType.LPWStr)] out string name);
        void SetTitle([MarshalAs(UnmanagedType.LPWStr)] string title);
        void SetOkButtonLabel([MarshalAs(UnmanagedType.LPWStr)] string text);
        void SetFileNameLabel([MarshalAs(UnmanagedType.LPWStr)] string label);
        void GetResult(out IShellItem item);
    }

    [ComImport, Guid("43826D1E-E718-42EE-BC55-A1E261C37BFE"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]
    interface IShellItem
    {
        void BindToHandler(IntPtr pbc, ref Guid bhid, ref Guid riid, out IntPtr ppv);
        void GetParent(out IShellItem item);
        void GetDisplayName(uint sigdn, [MarshalAs(UnmanagedType.LPWStr)] out string name);
    }

    [DllImport("shell32.dll", CharSet = CharSet.Unicode, PreserveSig = false)]
    static extern void SHCreateItemFromParsingName(string path, IntPtr pbc, ref Guid riid, out IShellItem item);

    public static string Pick(IntPtr owner, string title, string start)
    {
        try
        {
            var dlg = (IFileOpenDialog)new FileOpenDialogCom();
            dlg.SetOptions(0x20 | 0x40); // FOS_PICKFOLDERS | FOS_FORCEFILESYSTEM
            dlg.SetTitle(title);
            var dir = start;
            while (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir)) dir = System.IO.Path.GetDirectoryName(dir);
            if (!string.IsNullOrEmpty(dir))
            {
                var iid = typeof(IShellItem).GUID;
                IShellItem item;
                SHCreateItemFromParsingName(dir, IntPtr.Zero, ref iid, out item);
                dlg.SetFolder(item);
            }
            if (dlg.Show(owner) != 0) return null;
            IShellItem result;
            dlg.GetResult(out result);
            string path;
            result.GetDisplayName(0x80058000, out path); // SIGDN_FILESYSPATH
            return path;
        }
        catch { return null; }
    }
}
