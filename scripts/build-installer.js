// Builds afterterm's Windows installer: out\installer\afterterm-<version>-setup.exe.
//
//   node scripts/build-installer.js            the real installer
//   node scripts/build-installer.js --sandbox  "afterterm (test)", a throwaway copy
//                                              (see installer/electron-builder.cjs)
//   --skip-package                             reuse out\afterterm-win32-x64 as it is
//
// `npm run installer` runs it; `npm run release` runs it and then tags the version.
//
// Steps: package the app with Forge (out\afterterm-win32-x64, unless --skip-package),
// copy it to a staging folder, drop what never runs (debug symbols, the arm64
// node-pty files), and hand the folder to electron-builder, which wraps it in the
// NSIS installer whose pages are installer/pages.nsh. No 7-Zip, no hand steps.
//
// The sandbox build differs in four ways: its exe is afterterm-test.exe, so it can
// run beside the real afterterm; it installs to its own folder with its own
// uninstall entry; it carries resources\afterterm-sandbox.json, which points its
// data and its Claude Code settings at %LOCALAPPDATA%\afterterm-test; and it forces
// the Restricted execution policy on everything it starts and seeds the old (0.9.x)
// hook entries, which is the state Yogansh's machine was in on 2026-10-29.

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const args = process.argv.slice(2);
const sandbox = args.includes('--sandbox');
const skipPackage = args.includes('--skip-package');

const built = path.join(root, 'out', 'afterterm-win32-x64');
const stage = path.join(root, 'out', 'installer-stage', sandbox ? 'afterterm-test-win32-x64' : 'afterterm-win32-x64');

// build.js packages with Forge, after moving the previous build aside, and stops
// with a clear message when afterterm is running from that folder.
if (!skipPackage) {
  execFileSync(process.execPath, [path.join(root, 'scripts', 'build.js')], { stdio: 'inherit', cwd: root });
}
if (!fs.existsSync(path.join(built, 'afterterm.exe'))) {
  console.error(`No packaged app at ${built}. Run without --skip-package.`);
  process.exit(1);
}

console.log(`Staging ${path.relative(root, stage)}`);
fs.rmSync(stage, { recursive: true, force: true });
fs.cpSync(built, stage, { recursive: true });

// Never loaded at runtime: debug symbols and the other architecture's node-pty.
let pruned = 0;
(function prune(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) prune(p);
    else if (e.name.endsWith('.pdb')) { pruned += fs.statSync(p).size; fs.rmSync(p); }
  }
})(stage);
const arm64 = path.join(stage, 'resources', 'app', 'node_modules', 'node-pty', 'prebuilds', 'win32-arm64');
if (fs.existsSync(arm64)) fs.rmSync(arm64, { recursive: true, force: true });
console.log(`Pruned ${(pruned / 1048576).toFixed(0)} MB of debug symbols`);

// A stale sandbox file from a manual test must never reach a real installer.
const sandboxFile = path.join(stage, 'resources', 'afterterm-sandbox.json');
fs.rmSync(sandboxFile, { force: true });

if (sandbox) {
  fs.renameSync(path.join(stage, 'afterterm.exe'), path.join(stage, 'afterterm-test.exe'));
  fs.writeFileSync(sandboxFile, JSON.stringify({
    appId: 'com.afterterm.app.test',
    userDataDir: '%LOCALAPPDATA%\\afterterm-test\\data',
    claudeDir: '%LOCALAPPDATA%\\afterterm-test\\claude',
    executionPolicy: 'Restricted',
    seedLegacyHook: true,
  }, null, 2) + '\n');
}

execFileSync('npx', [
  'electron-builder', '--win', 'nsis', '--x64',
  '--prepackaged', JSON.stringify(stage),
  '--config', 'installer/electron-builder.cjs',
  '--publish', 'never',
], {
  stdio: 'inherit',
  cwd: root,
  shell: true,
  env: { ...process.env, AFTERTERM_INSTALLER_SANDBOX: sandbox ? '1' : '' },
});

// The face: afterterm Setup (installer/setup, WPF), compiled with the C# compiler
// that ships with Windows, the engine embedded in it as a resource.
const version = require(path.join(root, 'package.json')).version;
const base = sandbox ? 'afterterm-test' : 'afterterm';
const engine = path.join(root, 'out', 'installer', `${base}-${version}-engine.exe`);
const out = path.join(root, 'out', 'installer', `${base}-${version}-setup.exe`);

let expected = 0;
(function size(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) size(p); else expected += fs.statSync(p).size;
  }
})(stage);

const setupDir = path.join(root, 'installer', 'setup');
const genDir = path.join(root, 'out', 'installer-stage');
const config = path.join(genDir, 'Config.cs');
const cs = (s) => JSON.stringify(s); // a JSON string is a valid C# string literal here
fs.writeFileSync(config, [
  '// Generated by scripts/build-installer.js. Do not edit.',
  'static class Config {',
  `  public const string ProductName = ${cs(sandbox ? 'afterterm (test)' : 'afterterm')};`,
  `  public const string Version = ${cs(version)};`,
  `  public const string FolderName = ${cs(base)};`,
  `  public const string ExeName = ${cs(base + '.exe')};`,
  `  public const long ExpectedBytes = ${expected};`,
  '}',
  '',
].join('\n'));

const fw = path.join(process.env.WINDIR || 'C:\\Windows', 'Microsoft.NET', 'Framework64', 'v4.0.30319');
execFileSync(path.join(fw, 'csc.exe'), [
  '/nologo', '/target:winexe', '/optimize+', '/platform:anycpu',
  `/out:${out}`,
  `/win32icon:${path.join(root, 'assets', 'icon.ico')}`,
  `/win32manifest:${path.join(setupDir, 'app.manifest')}`,
  `/resource:${path.join(setupDir, 'Setup.xaml')},Setup.xaml`,
  `/resource:${engine},engine.exe`,
  `/r:${path.join(fw, 'WPF', 'PresentationFramework.dll')}`,
  `/r:${path.join(fw, 'WPF', 'PresentationCore.dll')}`,
  `/r:${path.join(fw, 'WPF', 'WindowsBase.dll')}`,
  `/r:${path.join(fw, 'System.Xaml.dll')}`,
  path.join(setupDir, 'Setup.cs'),
  config,
], { stdio: 'inherit' });
fs.rmSync(engine, { force: true });

console.log(`\nInstaller ready: ${path.relative(root, out)} (${(fs.statSync(out).size / 1048576).toFixed(0)} MB)`);
