#!/usr/bin/env node
/**
 * snapshot-sessions.js — freeze a human-readable record of the current afterterm
 * tabs / Claude sessions (with UUIDs) into docs/session-snapshots/<today>.md.
 *
 * Why: session.json is overwritten continuously and ConPTY can't be reconnected
 * after a restart, so a dated snapshot — crucially including each tab's Claude
 * session UUID — is what makes a past layout restorable. See the folder README.
 *
 * Usage:
 *   node scripts/snapshot-sessions.js                 # live %APPDATA% session.json
 *   node scripts/snapshot-sessions.js <path-to.json>  # a specific session file
 */
const fs = require("fs");
const path = require("path");

const appData = process.env.APPDATA || path.join(process.env.USERPROFILE || "", "AppData", "Roaming");
const srcPath = process.argv[2] || path.join(appData, "afterterm", "session.json");
const outDir = path.join(__dirname, "..", "docs", "session-snapshots");

let session;
try {
  session = JSON.parse(fs.readFileSync(srcPath, "utf8"));
} catch (e) {
  console.error(`Could not read session file: ${srcPath}\n  ${e.message}`);
  process.exit(1);
}

const tabs = session.tabs || [];
const groups = new Map((session.groups || []).map((g) => [g.id, g]));

const now = new Date();
const pad = (n) => String(n).padStart(2, "0");
const dateStr = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
const timeStr = `${pad(now.getHours())}:${pad(now.getMinutes())}`;

// Project directory for a tab: prefer its group's cwd (reliable), else the tab's cwd.
const projectOf = (tab) => {
  const g = tab.groupId && groups.get(tab.groupId);
  return (g && g.cwd) || tab.cwd || "(no cwd)";
};
const groupLabel = (tab) => {
  const g = tab.groupId && groups.get(tab.groupId);
  return g ? g.label : "(ungrouped)";
};

const claudeTabs = tabs.filter((t) => t.claudeSessionId);
const plainTabs = tabs.filter((t) => !t.claudeSessionId);

// Bucket by group label, preserving tab order.
function bucket(list) {
  const out = new Map();
  for (const t of list) {
    const key = groupLabel(t);
    if (!out.has(key)) out.set(key, { cwd: projectOf(t), tabs: [] });
    out.get(key).tabs.push(t);
  }
  return out;
}

const lines = [];
lines.push(`# afterterm session snapshot — ${dateStr} ${timeStr}`);
lines.push("");
lines.push("Generated by `scripts/snapshot-sessions.js` from the live session file.");
lines.push("Point-in-time capture, not authoritative state. See [README](README.md).");
lines.push("");
lines.push(`- Source: \`${srcPath}\``);
lines.push(`- Tabs: ${tabs.length} (${claudeTabs.length} Claude sessions, ${plainTabs.length} plain shells)`);
lines.push(`- Active tab: \`${session.activeTabId || "(none)"}\``);
lines.push("");

lines.push("## Claude sessions (resumable — UUIDs included)");
lines.push("");
if (claudeTabs.length === 0) {
  lines.push("_None._");
  lines.push("");
} else {
  for (const [label, info] of bucket(claudeTabs)) {
    lines.push(`### ${label} — \`${info.cwd}\``);
    for (const t of info.tabs) {
      const title = (t.title || "(untitled)").trim();
      // Guard: afterterm can persist a backslash-stripped claudeCwd (e.g.
      // "D:Tinkeringafterterm"). If it has no path separator, it's garbage —
      // fall back to the reliable group cwd.
      let cwd = t.claudeCwd;
      if (!cwd || !/[\\/]/.test(cwd)) cwd = projectOf(t);
      lines.push(`- **${title}**`);
      lines.push(`  - resume: \`claude --resume ${t.claudeSessionId}\` in \`${cwd}\``);
    }
    lines.push("");
  }
}

lines.push("---");
lines.push("");
lines.push("## Plain shells (no Claude session)");
lines.push("");
if (plainTabs.length === 0) {
  lines.push("_None._");
} else {
  for (const [label, info] of bucket(plainTabs)) {
    lines.push(`- **${label}** — \`${info.cwd}\` (${info.tabs.length} tab${info.tabs.length === 1 ? "" : "s"})`);
  }
}
lines.push("");

const outPath = path.join(outDir, `${dateStr}.md`);
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath}`);
console.log(`  ${tabs.length} tabs — ${claudeTabs.length} Claude sessions, ${plainTabs.length} plain shells`);
